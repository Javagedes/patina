#[cfg_attr(coverage, coverage(off))]
#[patina_test]
fn test_hash_hash_all_known_answers(hash: Service<dyn Hash>) -> Result {
    let vectors: [(HashAlgorithm, &[u8]); 4] = [
        (HashAlgorithm::Sha1, &SHA1_ABC),
        (HashAlgorithm::Sha256, &SHA256_ABC),
        (HashAlgorithm::Sha384, &SHA384_ABC),
        (HashAlgorithm::Sha512, &SHA512_ABC),
    ];
    for (algorithm, expected) in vectors {
        let digest = hash.hash_all(algorithm, b"abc");
        u_assert!(digest.is_ok(), "hash_all failed");
        u_assert_eq!(digest.unwrap().as_slice(), expected, "hash_all digest mismatch");
    }
    Ok(())
}

#[cfg_attr(coverage, coverage(off))]
#[patina_test]
fn test_hash_new_hash_streams_and_duplicates(hash: Service<dyn Hash>) -> Result {
    for (algorithm, expected) in [(HashAlgorithm::Sha1, &SHA1_ABC[..]), (HashAlgorithm::Sha512, &SHA512_ABC[..])] {
        let context = hash.new_hash(algorithm);
        u_assert!(context.is_ok(), "new_hash failed");
        let mut context = context.unwrap();
        for chunk in [b"a".as_slice(), b"b", b"c"] {
            u_assert!(context.update(chunk).is_ok(), "update failed");
        }
        u_assert_eq!(context.finalize().ok().as_deref(), Some(expected), "streamed digest mismatch");
    }

    let mut context = hash.new_hash(HashAlgorithm::Sha256).map_err(|_| "new_hash failed")?;
    u_assert!(context.update(b"a").is_ok(), "update failed");
    let copy = context.duplicate().map_err(|_| "duplicate failed")?;
    u_assert!(context.update(b"bc").is_ok(), "update failed");
    u_assert_eq!(context.finalize().ok().as_deref(), Some(&SHA256_ABC[..]), "original digest mismatch");
    u_assert_eq!(copy.finalize().ok().as_deref(), Some(&SHA256_A[..]), "duplicated digest mismatch");
    Ok(())
}

#[cfg_attr(coverage, coverage(off))]
#[patina_test]
fn test_hash_mac_known_answers(hash: Service<dyn Hash>) -> Result {
    let vectors: [(HashAlgorithm, &[u8]); 2] =
        [(HashAlgorithm::Sha256, &HMAC_SHA256_JEFE), (HashAlgorithm::Sha384, &HMAC_SHA384_JEFE)];
    for (digest, expected) in vectors {
        let algorithm = MacAlgorithm::Hmac(digest);
        u_assert_eq!(hash.mac_all(algorithm, HMAC_KEY, HMAC_DATA).ok().as_deref(), Some(expected), "mac_all mismatch");

        let mut context = hash.new_mac(algorithm, HMAC_KEY).map_err(|_| "new_mac failed")?;
        let (first, second) = HMAC_DATA.split_at(10);
        u_assert!(context.update(first).is_ok(), "update failed");
        u_assert!(context.update(second).is_ok(), "update failed");
        u_assert_eq!(context.finalize().ok().as_deref(), Some(expected), "streamed MAC mismatch");
    }
    Ok(())
}

#[cfg_attr(coverage, coverage(off))]
#[patina_test]
fn test_hash_derive_key_known_answers(hash: Service<dyn Hash>) -> Result {
    let sha256 = HashAlgorithm::Sha256;

    let mut okm = [0u8; 42];
    let result = hash.derive_key(KdfAlgorithm::Hkdf { digest: sha256 }, &HKDF_IKM, &HKDF_SALT, &HKDF_INFO, &mut okm);
    u_assert!(result.is_ok(), "HKDF failed");
    u_assert_eq!(okm, HKDF_SHA256_OKM, "HKDF output mismatch");

    let mut prk = [0u8; 32];
    let result = hash.derive_key(KdfAlgorithm::HkdfExtract { digest: sha256 }, &HKDF_IKM, &HKDF_SALT, &[], &mut prk);
    u_assert!(result.is_ok(), "HKDF extract failed");
    u_assert_eq!(prk, HKDF_SHA256_PRK, "HKDF extract output mismatch");

    let mut okm = [0u8; 42];
    let result = hash.derive_key(KdfAlgorithm::HkdfExpand { digest: sha256 }, &prk, &[], &HKDF_INFO, &mut okm);
    u_assert!(result.is_ok(), "HKDF expand failed");
    u_assert_eq!(okm, HKDF_SHA256_OKM, "HKDF expand output mismatch");

    let mut key = [0u8; 64];
    let pbkdf2 = KdfAlgorithm::Pbkdf2 { digest: sha256, iterations: 1 };
    u_assert!(hash.derive_key(pbkdf2, b"passwd", b"salt", &[], &mut key).is_ok(), "PBKDF2 failed");
    u_assert_eq!(key, PBKDF2_SHA256, "PBKDF2 output mismatch");
    Ok(())
}
